import "server-only";

import { randomUUID } from "node:crypto";

import { ImageKitStorageProvider } from "@/lib/storage/imagekit-storage-provider";

import type { StorageProvider } from "./storage-provider";

/**
 * Direct-upload image flow shared by product galleries and store branding:
 * the server issues a key under a tenant-scoped prefix, the browser uploads to
 * ImageKit, and before any database association the server re-checks that the
 * key is under the expected prefix and that the stored asset matches type/size.
 */
export const IMAGE_MAX_SIZE_IN_BYTES = 5 * 1024 * 1024;
export const imageContentTypes = {
  "image/jpeg": "jpg",
  "image/png": "png",
  "image/webp": "webp",
} as const;
export type ImageContentType = keyof typeof imageContentTypes;

/** File names generated by `createImageUploadUrl` (UUID + allowed extension). */
export const GENERATED_IMAGE_NAME = /^[0-9a-f-]{36}\.(jpg|png|webp)$/;
/** Looser pattern accepted for product galleries (single path segment, allowed extension). */
export const SAFE_IMAGE_NAME = /^[a-zA-Z0-9_-]+\.(jpg|png|webp)$/;

export function isStorageKeyUnderPrefix(storageKey: string, prefix: string, namePattern: RegExp): boolean {
  return storageKey.startsWith(prefix) && namePattern.test(storageKey.slice(prefix.length));
}

export async function createImageUploadUrl(input: {
  prefix: string;
  contentType: ImageContentType;
  storage?: StorageProvider;
}) {
  const storage = input.storage ?? new ImageKitStorageProvider();
  const key = `${input.prefix}${randomUUID()}.${imageContentTypes[input.contentType]}`;
  const result = await storage.createUploadUrl({
    key,
    contentType: input.contentType,
    maxSizeInBytes: IMAGE_MAX_SIZE_IN_BYTES,
  });
  return { url: result.url, key: result.key, expiresAt: result.expiresAt.toISOString(), fields: result.fields };
}

export type AttachVerifiedAssetResult<T> = { ok: true; value: T } | { ok: false; reason: "FOREIGN_KEY" };

/**
 * Verifies ownership (prefix) and the uploaded asset itself, then runs
 * `persist` (the caller's transactional association). Verification failures
 * from the provider are thrown as-is.
 */
export async function attachVerifiedAsset<T>(input: {
  storageKey: string;
  fileId: string;
  prefix: string;
  namePattern: RegExp;
  persist: () => Promise<T>;
  storage?: StorageProvider;
}): Promise<AttachVerifiedAssetResult<T>> {
  if (!isStorageKeyUnderPrefix(input.storageKey, input.prefix, input.namePattern)) {
    return { ok: false, reason: "FOREIGN_KEY" };
  }
  const storage = input.storage ?? new ImageKitStorageProvider();
  await storage.verifyImage({
    key: input.storageKey,
    fileId: input.fileId,
    maxSizeInBytes: IMAGE_MAX_SIZE_IN_BYTES,
    contentTypes: Object.keys(imageContentTypes),
  });
  return { ok: true, value: await input.persist() };
}
