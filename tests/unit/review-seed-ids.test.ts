import { describe, expect, it } from "vitest";
import { z } from "zod";

import { REVIEW_ID_PREFIX, reviewId } from "../../scripts/review-seed-ids";

describe("review seed ids", () => {
  it("pass the cuid validation used by every Server Action", () => {
    for (const [kind, key] of [
      ["product", "capacete"],
      ["viewer-address", "user:0"],
      ["order", "MS-REVIEW-0001"],
    ] as const) {
      expect(z.cuid().safeParse(reviewId(kind, key)).success).toBe(true);
    }
  });

  it("stay distinguishable from ids generated by Prisma today", () => {
    expect(reviewId("product", "x").startsWith(REVIEW_ID_PREFIX)).toBe(true);
    // Real cuids currently start with "cm" (timestamp in base 36); the review prefix never collides.
    expect("cmuzippl6001mdwt1apkeqa2e".startsWith(REVIEW_ID_PREFIX)).toBe(false);
  });
});
